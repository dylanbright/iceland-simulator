"""Rebuild art/ and css/art.css from the purchased artwork pack (folder PNG/).

Why data URIs: the game is opened straight from disk (file://), and browsers refuse to
load CSS mask images from other files over file:// (CORS). Inlined data: URIs always work.
Run from the project folder:  python tools/build_art.py
Needs: pip install pillow numpy
"""
import base64, io, os
import numpy as np
from PIL import Image

SRC = os.environ.get('ART_SRC', 'PNG/')
OUT_PNG, OUT_CSS = 'art/', 'css/art.css'

def load(n): return Image.open(SRC + n + '.png').convert('RGBA')
def white_ink(im): return np.array(im)[..., 3].astype(float)            # keep the shape's alpha
def dark_ink(im):                                                         # dark lines become the ink
    a = np.array(im).astype(float); return ((255 - a[..., :3].mean(axis=2)) * a[..., 3] / 255).clip(0, 255)
def crop(a):
    ys, xs = np.where(a > 8); return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
def mask(a, maxdim):
    im = Image.fromarray(a.astype('uint8'), 'L'); im.thumbnail((maxdim, maxdim), Image.LANCZOS)
    out = Image.new('LA', im.size, (255, 0)); out.putalpha(im); return out

pieces = {}
# braid: rotate the vertical strip, then cut exactly one period so it tiles with no seam
br = np.rot90(crop(white_ink(load('Borre Style 007 A'))))
big = mask(br, 2000); col = np.array(big.split()[-1]).astype(float).sum(axis=0)
period = min(range(300, 480), key=lambda p: np.abs(col[600:1500] - col[600 + p:1500 + p]).mean())
tile = big.crop((410, 0, 410 + period, big.height)); pieces['braid'] = tile.resize((round(period * 96 / big.height), 96), Image.LANCZOS)
for k, n in {'knot-b': 'Borre Style 006 B', 'knot-d': 'Borre Style 006 D', 'knot-g': 'Borre Style 006 G'}.items():
    pieces[k] = mask(crop(white_ink(load(n))), 170)
pieces['beast-ring'] = mask(crop(white_ink(load('Borre Style 005'))), 400)
pieces['warriors'] = mask(crop(dark_ink(load('Helmet Plate 002'))), 400)
pieces['bracteate'] = mask(crop(dark_ink(load('Gold Bracteate 001'))), 360)
pieces['shield-bearer'] = mask(crop(dark_ink(load('Figurative 001'))), 340)

os.makedirs(OUT_PNG, exist_ok=True)
css = ['/* Generated by tools/build_art.py. Do not edit by hand. */', ':root {']
for k, im in pieces.items():
    buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
    im.save(OUT_PNG + k + '.png', optimize=True)
    css.append(f'  --art-{k}: url("data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}");')
css.append('}')
# favicon: the Borre knot in basalt on fog (a plain image, since tabs cannot tint masks)
k = Image.fromarray(crop(white_ink(load('Borre Style 006 I'))).astype('uint8'), 'L').resize((44, 44), Image.LANCZOS)
fav = Image.new('RGBA', (64, 64), (221, 225, 222, 255)); fav.paste(Image.new('RGBA', (44, 44), (36, 40, 42, 255)), (10, 10), k)
fav.save(OUT_PNG + 'favicon.png', optimize=True)
open(OUT_CSS, 'w').write('\n'.join(css) + '\n')
print('wrote', OUT_CSS, os.path.getsize(OUT_CSS) // 1024, 'KB')
